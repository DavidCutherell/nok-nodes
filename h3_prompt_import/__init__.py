"""H3 Prompt Import.

A canvas node that takes a dropped video or image generated by ComfyUI and
reads the prompt stored inside it. A dialog then shows each prompt text next
to what the chosen destination on the canvas holds now, and copies over the
parts the person ticks. It works with any prompt tool: a node of the same
type can get all of its fields back, and any text box can take the text. The
Fantastic Prompt Builder is compared and copied section by section.

This file is the server side: the node definition and the route that reads
a posted file. Choosing, comparing and writing happen in the browser.

The node itself never runs: the browser marks it virtual, so it is left out
of the queued graph and out of saved metadata.

Browser side: `web/h3_prompt_import.js` at the pack root.
"""

import asyncio
import os

from .extract import analyse, read_metadata

try:
    from server import PromptServer
    from aiohttp import web
except Exception:  # pragma: no cover - only outside ComfyUI
    PromptServer = None
    web = None


class H3PromptImport:
    CATEGORY = "conditioning/video_models"
    DESCRIPTION = (
        "Drop a video or image that ComfyUI generated onto this node to reuse "
        "its prompt. A dialog lists each prompt text saved in the file. You "
        "choose where each one goes and, side by side with what is there now, "
        "tick which parts to keep and which to take. Works with any prompt "
        "tool; the Fantastic Prompt Builder is handled section by section. "
        "Nothing is copied until you confirm, nothing is queued, and the "
        "dropped file is not stored."
    )
    RETURN_TYPES = ()
    FUNCTION = "noop"

    @classmethod
    def INPUT_TYPES(cls):
        return {"required": {}}

    def noop(self, **kwargs):
        return ()


def describe_node(class_type):
    """Input types, multiline text inputs and output types of an installed node type."""
    try:
        import nodes

        cls = nodes.NODE_CLASS_MAPPINGS.get(class_type)
        if cls is None:
            return None
        if hasattr(cls, "GET_NODE_INFO_V1"):          # nodes written against the v3 schema
            node_info = cls.GET_NODE_INFO_V1()
            spec, outputs = node_info.get("input") or {}, node_info.get("output") or []
        else:
            spec, outputs = cls.INPUT_TYPES(), cls.RETURN_TYPES
        inputs, multiline = {}, []
        for section in ("required", "optional"):
            for name, decl in (spec.get(section) or {}).items():
                listed = isinstance(decl, (list, tuple)) and len(decl) > 0
                kind = decl[0] if listed else decl
                inputs[name] = kind if isinstance(kind, str) else "COMBO"
                options = decl[1] if listed and len(decl) > 1 and isinstance(decl[1], dict) else {}
                if options.get("multiline"):
                    multiline.append(name)
        return {"inputs": inputs, "multiline": multiline, "outputs": [str(o) for o in outputs]}
    except Exception:
        return None


if PromptServer is not None and web is not None:

    @PromptServer.instance.routes.post("/h3_prompt_import/extract")
    async def h3_prompt_import_extract(request):
        """Read-only: parse the posted file in memory, return its prompt nodes."""
        name = os.path.basename(request.query.get("name") or "file")
        data = await request.read()
        if not data:
            return web.json_response({"ok": False, "error": "The file arrived empty."})
        try:
            found, errors = await asyncio.to_thread(read_metadata, data, name)
            result = analyse(found, errors, name, describe_node)
        except Exception as exc:
            result = {"ok": False, "error": f"Could not read that file: {exc}"}
        outcome = f"found {len(result['nodes'])} prompt node(s)" if result.get("ok") else "nothing to copy"
        print(f"[H3 Prompt Import] {name}: {outcome}", flush=True)
        return web.json_response(result, headers={"Cache-Control": "no-store"})


NODE_CLASS_MAPPINGS = {"H3PromptImport": H3PromptImport}
NODE_DISPLAY_NAME_MAPPINGS = {"H3PromptImport": "H3 Prompt Import (drop a video or image)"}

__all__ = ["NODE_CLASS_MAPPINGS", "NODE_DISPLAY_NAME_MAPPINGS"]
